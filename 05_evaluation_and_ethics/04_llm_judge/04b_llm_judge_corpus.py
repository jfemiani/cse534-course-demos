"""Demo: Table 1's n-gram order sweep, extended with an LLM-as-judge column,
instead of the three toy candidates 04_llm_judge.py judged.

See 04b_llm_judge_corpus.md for the full explanation.
Reuses the same corpus, split, training, and generation logic as
03c_multi_metric_corpus.py; only the scoring at the end is different.
"""

import math
import os
import random
from collections import Counter
from urllib.request import urlopen

from openai import OpenAI
from pydantic import BaseModel

client = OpenAI()
model = os.getenv("OPENAI_MODEL", "gpt-5.6")

CORPUS_URL = "https://raw.githubusercontent.com/karpathy/char-rnn/master/data/tinyshakespeare/input.txt"
PAD = "^"
END = "$"
ORDERS = [2, 3, 4, 5, 6, 7, 8]
HELD_OUT_FRACTION = 0.1
FLOOR_PROBABILITY = 1e-4
PROMPT_CHARS = 20
CONTINUATION_CHARS = 40
SAMPLE_SIZE = 10  # small on purpose: this demo makes one real API call per block per order
GROUP_SIZE = 5
BEST_ORDER = 3
RANDOM_SEED = 42


class Judgment(BaseModel):
    correct: bool
    quality: int  # 1 (bad) to 5 (excellent)
    reason: str


def judge(prompt: str, reference: str, candidate: str) -> Judgment:
    text = (
        f"Prompt (start of a line from a Shakespeare play): {prompt!r}\n"
        f"Reference continuation (what actually comes next): {reference!r}\n"
        f"Candidate continuation (generated by a small n-gram model): {candidate!r}\n\n"
        "Judge whether the candidate is a plausible continuation of the prompt, "
        "compared to the reference. Consider whether it forms real words and "
        "plausible Shakespearean phrasing, not just whether it matches the "
        "reference exactly."
    )
    response = client.responses.parse(model=model, input=text, text_format=Judgment)
    return response.output_parsed


def load_blocks() -> list[str]:
    with urlopen(CORPUS_URL) as response:
        text = response.read().decode("utf-8")
    return [block.strip() for block in text.split("\n\n") if block.strip()]


def train_counts(blocks: list[str], order: int) -> dict[str, dict[str, int]]:
    counts: dict[str, dict[str, int]] = {}
    for block in blocks:
        sequence = PAD * order + block + END
        for i in range(len(sequence) - order):
            context = sequence[i:i + order]
            next_char = sequence[i + order]
            counts.setdefault(context, {})
            counts[context][next_char] = counts[context].get(next_char, 0) + 1
    return counts


def evaluate(counts: dict[str, dict[str, int]], blocks: list[str], order: int) -> tuple[float, float]:
    total_bits = 0.0
    total_chars = 0
    misses = 0
    for block in blocks:
        sequence = PAD * order + block + END
        for i in range(len(sequence) - order):
            context = sequence[i:i + order]
            next_char = sequence[i + order]
            context_counts = counts.get(context)
            if not context_counts or next_char not in context_counts:
                p, miss = FLOOR_PROBABILITY, True
            else:
                p, miss = context_counts[next_char] / sum(context_counts.values()), False
            total_bits += -math.log2(p)
            total_chars += 1
            misses += miss
    return total_bits / total_chars, misses / total_chars


def generate(counts: dict[str, dict[str, int]], order: int, prompt: str, length: int, fallback_char: str) -> str:
    text = PAD * order + prompt
    generated = []
    for _ in range(length):
        context_counts = counts.get(text[-order:])
        if context_counts:
            chars, weights = zip(*context_counts.items())
            next_char = random.choices(chars, weights=weights)[0]
        else:
            next_char = fallback_char
        generated.append(next_char)
        text += next_char
    return "".join(generated)


blocks = load_blocks()
split = int(len(blocks) * (1 - HELD_OUT_FRACTION))
train_blocks, held_out_blocks = blocks[:split], blocks[split:]

min_length = PROMPT_CHARS + CONTINUATION_CHARS
eligible_blocks = [block for block in held_out_blocks if len(block) >= min_length]
random.seed(RANDOM_SEED)
sample_blocks = random.sample(eligible_blocks, SAMPLE_SIZE)
fallback_char = Counter("".join(train_blocks)).most_common(1)[0][0]

print(f"{len(train_blocks)} training blocks, {len(held_out_blocks)} held-out blocks, "
      f"judging {SAMPLE_SIZE} generated continuations per order\n")

results_by_order: dict[int, list[tuple[Judgment, str, str, str]]] = {}
print(f"{'order':>5s} {'contexts':>9s} {'miss rate':>10s} {'cross-ent':>10s} {'perplexity':>11s} "
      f"{'judge: correct':>15s} {'judge: quality':>15s}")
for order in ORDERS:
    counts = train_counts(train_blocks, order)
    cross_entropy, miss_rate = evaluate(counts, held_out_blocks, order)

    judgments = []
    for block in sample_blocks:
        prompt, reference = block[:PROMPT_CHARS], block[PROMPT_CHARS:PROMPT_CHARS + CONTINUATION_CHARS]
        candidate = generate(counts, order, prompt, CONTINUATION_CHARS, fallback_char)
        verdict = judge(prompt, reference, candidate)
        judgments.append((verdict, prompt, candidate, reference))
    results_by_order[order] = judgments

    correct_rate = sum(v.correct for v, *_ in judgments) / len(judgments)
    avg_quality = sum(v.quality for v, *_ in judgments) / len(judgments)
    perplexity = 2 ** cross_entropy
    print(f"{order:5d} {len(counts):9d} {miss_rate:10.2%} {cross_entropy:10.3f} {perplexity:11.2f} "
          f"{correct_rate:15.1%} {avg_quality:15.2f}")

judgments = sorted(results_by_order[BEST_ORDER], key=lambda item: item[0].quality)
lemons, apples, cherries = judgments[:GROUP_SIZE], judgments[len(judgments) // 2 - GROUP_SIZE // 2:len(judgments) // 2 - GROUP_SIZE // 2 + GROUP_SIZE], judgments[-GROUP_SIZE:]

print(f"\norder={BEST_ORDER} generated continuations, sorted by judge quality (higher is better)\n")
for label, group in [("CHERRIES (highest quality)", cherries), ("APPLES (median)", apples), ("LEMONS (lowest quality)", lemons)]:
    print(f"--- {label} ---")
    for verdict, prompt, candidate, reference in group:
        print(f"correct: {verdict.correct}   quality: {verdict.quality}/5   reason: {verdict.reason}")
        print(f"  prompt:     {prompt!r}")
        print(f"  candidate:  {candidate!r}")
        print(f"  reference:  {reference!r}")
    print()
